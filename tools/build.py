# Builds one page per comparison, with tabs for its scenes, for every mod folder with a comparisons.json:
# <mod>/<slug>/index.html (data inline, so the pages also work opened straight from disk), plus
# <mod>/previews/<slug>.jpg, the image shown when a link is shared (cut from the first scene, or "main_view" if the
# comparison sets one). A scene and pair can be linked with #<scene>/<left>-<right>. There is no index page; the pages are
# linked from elsewhere (each mod's README); <mod>/LINKS.md lists them all, ready to copy.
#
#   python tools/build.py
#
# Set base_url in site.json to the published address (e.g. https://user.github.io/repo/) so that link previews on
# Discord and forums can find the preview image; they need a full address.
import html, json, os
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESERVED = {'images', 'previews'}   # folder names inside a mod folder
site = json.load(open(os.path.join(ROOT, 'site.json'), encoding='utf-8'))
esc = lambda s: html.escape(s, quote=True)


def preview(mod, c, v):
    #1200x630 split image: left half of the opening pair's left image, right half of its right image
    ims = v['images']; a, b = v['pair'][0] - 1, v['pair'][1] - 1
    W, H = 1200, 630
    def fit(src):
        im = Image.open(os.path.join(ROOT, mod, src)).convert('RGB')
        s = max(W / im.width, H / im.height)
        im = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
        x, y = (im.width - W) // 2, (im.height - H) // 2
        return im.crop((x, y, x + W, y + H))
    left, right = fit(ims[a]['src']), fit(ims[b]['src'])
    out = left.copy(); out.paste(right.crop((W // 2, 0, W, H)), (W // 2, 0))
    ImageDraw.Draw(out).rectangle((W // 2 - 1, 0, W // 2 + 1, H), fill='white')
    os.makedirs(os.path.join(ROOT, mod, 'previews'), exist_ok=True)
    rel = f'previews/{c["slug"]}.jpg'
    out.save(os.path.join(ROOT, mod, rel), quality=85, optimize=True)
    return rel


def page(mod, title_mod, c, prev):
    root, top = '../', '../../'   # the mod's folder (images) and the site's top (shared assets)
    title = f'{title_mod} | {c["title"]}'
    img = (site['base_url'] + mod + '/' if site.get('base_url') else root) + prev
    n = max(len(v['images']) for v in c['views'])
    payload = json.dumps({'main_view': c.get('main_view'), 'views': [{k: v[k] for k in ('slug', 'name', 'pair', 'images')}
                                                                     for v in c['views']]},
                         ensure_ascii=False).replace('</', '<\\/')   # no closing tag inside the script element
    return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)}</title>
<meta name="description" content="{esc(c["description"])}">
<meta property="og:type" content="website">
<meta property="og:title" content="{esc(title)}">
<meta property="og:description" content="{esc(c["description"])}">
<meta property="og:image" content="{esc(img)}">
<meta name="twitter:card" content="summary_large_image">
<link rel="stylesheet" href="{top}assets/compare.css">
</head>
<body data-root="{root}">
<main>
<header>
<h1>{esc(c["title"])}</h1>
<p>{esc(c["description"])}</p>
</header>
<nav id="views"></nav>
<div class="controls">
<label for="left">Left</label><select id="left"></select>
<label for="right">Right</label><select id="right"></select>
<span class="spacer"></span>
<button id="full">Full screen</button>
</div>
<div id="wrap">
<div id="viewer"></div>
<div id="line" hidden></div>
<span class="lab" id="labA"></span><span class="lab" id="labB"></span>
<button id="exitfull">Exit full screen</button>
</div>
<p class="hint">Move the mouse over the image to compare (on touch screens, drag the line). Scroll or pinch to zoom, drag to
pan. Keys <kbd>1</kbd>&ndash;<kbd>{n}</kbd> show one image on its own, <kbd>0</kbd> goes back.</p>
</main>
<script id="data" type="application/json">{payload}</script>
<script src="{top}assets/vendor/openseadragon/openseadragon.min.js"></script>
<script src="{top}assets/vendor/curtain-sync/openseadragon-curtain-sync.js"></script>
<script src="{top}assets/compare.js"></script>
</body>
</html>
'''


for mod in sorted(os.listdir(ROOT)):
    path = os.path.join(ROOT, mod, 'comparisons.json')
    if not os.path.isfile(path):
        continue
    data = json.load(open(path, encoding='utf-8'))
    base = site['base_url'] + mod + '/' if site.get('base_url') else ''   # relative to LINKS.md until the address is set
    links = [f'# {data["title"]}: comparison pages', '',
             'Generated by tools/build.py.' + ('' if site.get('base_url') else ' Set base_url in site.json for full addresses.')]
    for c in data['comparisons']:
        assert c['slug'] not in RESERVED, f'{mod}: slug {c["slug"]} clashes with a folder name'
        links += ['', f'- **[{c["title"]}]({base}{c["slug"]}/)**: ' +
                  ', '.join(f'[{v["name"].lower()}]({base}{c["slug"]}/#{v["slug"]})' for v in c['views'])]
        main = next((v for v in c['views'] if v['slug'] == c.get('main_view')), c['views'][0])
        d = os.path.join(ROOT, mod, c['slug']); os.makedirs(d, exist_ok=True)
        open(os.path.join(d, 'index.html'), 'w', encoding='utf-8').write(page(mod, data['title'], c, preview(mod, c, main)))
        print(f'built {mod}/{c["slug"]}/')
    open(os.path.join(ROOT, mod, 'LINKS.md'), 'w', encoding='utf-8').write(chr(10).join(links) + chr(10))
